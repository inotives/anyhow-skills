#!/usr/bin/env python3
"""Generate a read-only task DAG dashboard from a feature's task READMEs."""

import json
import re
import sys
from pathlib import Path


MARKER = "<!-- Generated by trinary-agents; do not edit. -->"
HANDOFF_NAME = re.compile(r"^(\d{8}_\d{6})--(?P<role>.+?)-handoff-(?P<sequence>\d+)\.md$")
HANDOFF_FIELD = re.compile(r"^-\s+(Role|Recipient|Outcome|Timestamp \(UTC\)):\s*(.*?)\s*$", re.I)


def scalar(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def read_task(readme):
    text = readme.read_text(encoding="utf-8")
    match = re.match(r"\A---\s*\n(.*?)\n---(?:\n|$)", text, re.S)
    if not match:
        raise ValueError(f"{readme}: missing YAML frontmatter")
    fields = {}
    lines = match.group(1).splitlines()
    for index, line in enumerate(lines):
        field = re.match(r"^(id|title|status|depends_on):\s*(.*)$", line)
        if not field:
            continue
        key, value = field.groups()
        if key != "depends_on":
            fields[key] = scalar(value)
            continue
        if value.startswith("[") and value.endswith("]"):
            inner = value[1:-1].strip()
            fields[key] = [scalar(part) for part in inner.split(",") if part.strip()]
        elif value:
            raise ValueError(f"{readme}: depends_on must be [] or a YAML list")
        else:
            dependencies = []
            for item in lines[index + 1 :]:
                if not item.strip():
                    continue
                list_item = re.match(r"^\s+-\s+(.+?)\s*$", item)
                if list_item:
                    dependencies.append(scalar(list_item.group(1)))
                elif not item.startswith(" "):
                    break
            fields[key] = dependencies
    missing = [key for key in ("id", "title", "status", "depends_on") if key not in fields]
    if missing:
        raise ValueError(f"{readme}: missing frontmatter fields: {', '.join(missing)}")
    return fields


def read_handoffs(handoffs_dir, task):
    if not handoffs_dir.is_dir():
        return []
    candidates = []
    for path in handoffs_dir.glob("*.md"):
        match = HANDOFF_NAME.match(path.name)
        if match and path.is_file() and not path.is_symlink():
            candidates.append((match.group(1), int(match.group("sequence")), path, match.group("role")))
    handoffs = []
    for stamp, sequence, path, name_role in candidates:
        text = path.read_text(encoding="utf-8")
        metadata = {}
        for line in text.splitlines():
            match = HANDOFF_FIELD.match(line)
            if match:
                metadata[match.group(1).lower()] = scalar(match.group(2))
        summary_match = re.search(r"^## Summary\s*\n(.*?)(?=^## |\Z)", text, re.M | re.S)
        summary = " ".join(line.strip() for line in summary_match.group(1).splitlines() if line.strip()) if summary_match else ""
        filename_timestamp = f"{stamp[:4]}-{stamp[4:6]}-{stamp[6:8]}T{stamp[9:11]}:{stamp[11:13]}:{stamp[13:15]}Z"
        handoffs.append({
            "task_id": task["id"],
            "task_title": task["title"],
            "role": metadata.get("role") or name_role.replace("-", " ").title(),
            "recipient": metadata.get("recipient", ""),
            "outcome": metadata.get("outcome") or "Not recorded",
            "timestamp": metadata.get("timestamp (utc)") or filename_timestamp,
            "summary": summary,
            "filename": path.name,
            "sort_timestamp": stamp,
            "sequence": sequence,
        })
    return handoffs


def latest_handoff(handoffs):
    if not handoffs:
        return {"role": "—", "recipient": "", "outcome": "No handoff yet", "timestamp": "—", "summary": ""}
    latest = max(handoffs, key=lambda item: (item["sort_timestamp"], item["sequence"], item["filename"]))
    return {key: latest[key] for key in ("role", "recipient", "outcome", "timestamp", "summary")}


def current_owner(status, handoff):
    if status == "done":
        return "Completed"
    if status == "blocked":
        return "Human"
    recipient = handoff.get("recipient", "").strip()
    if recipient.lower() not in {"", "—", "-", "none", "null", "unknown", "n/a"}:
        aliases = {"project-manager": "Project manager", "reviewer": "Reviewer", "worker": "Worker", "human": "Human"}
        return aliases.get(recipient.lower(), recipient.replace("-", " ").title())
    fallbacks = {"blocked": "Human", "needs_human": "Human", "waiting_human": "Human", "review": "Reviewer", "in_progress": "Worker"}
    return fallbacks.get(status, "Project manager")


def kanban_lane(status):
    if status in {"in_progress", "changes_requested"}:
        return "Worker"
    if status == "review":
        return "Reviewer"
    if status == "done":
        return "Done"
    return "Project manager"


def load_tasks(feature_dir):
    tasks_dir = feature_dir / "tasks"
    if not tasks_dir.is_dir():
        raise ValueError(f"{tasks_dir}: task directory does not exist")
    tasks = []
    for path in sorted(tasks_dir.glob("T-*")):
        if not (path / "README.md").is_file():
            continue
        task = read_task(path / "README.md")
        task["handoffs"] = read_handoffs(path / "handoffs", task)
        task["latest_handoff"] = latest_handoff(task["handoffs"])
        task["owner"] = current_owner(task["status"], task["latest_handoff"])
        task["lane"] = kanban_lane(task["status"])
        tasks.append(task)
    if len(tasks) < 2:
        return []
    by_id = {task["id"]: task for task in tasks}
    if len(by_id) != len(tasks):
        raise ValueError("task IDs must be unique")
    for task in tasks:
        unknown = set(task["depends_on"]) - by_id.keys()
        if unknown:
            raise ValueError(f"{task['id']}: unknown dependencies: {', '.join(sorted(unknown))}")

    visiting = set()
    ranks = {}

    def rank(task_id):
        if task_id in visiting:
            raise ValueError(f"dependency cycle includes {task_id}")
        if task_id not in ranks:
            visiting.add(task_id)
            deps = by_id[task_id]["depends_on"]
            ranks[task_id] = 0 if not deps else 1 + max(rank(dep) for dep in deps)
            visiting.remove(task_id)
        return ranks[task_id]

    for task in tasks:
        rank(task["id"])
    return tasks


